export function searchFood(query) {
  if (!query) return [];
  const lowerQuery = query.toLowerCase();
  return indianFoodDB.filter(f => f.name.toLowerCase().includes(lowerQuery) || f.category.toLowerCase().includes(lowerQuery));
}

export function getFoodById(id) {
  return indianFoodDB.find(f => f.id === id);
}

export function getFoodCategoryList() {
  const categories = new Set(indianFoodDB.map(f => f.category));
  return [...categories];
}
